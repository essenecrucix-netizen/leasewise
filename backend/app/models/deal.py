"""
ORM model — market_deals.

The "what people actually paid" database. Phase 1.4 starts populating it
via the LeaseHackr crawler (Canadian deals only, US deals skipped and
logged in lh_crawl_log). The rater queries it for percentile scoring
once the row count crosses MIN_COMPARABLES_FOR_PERCENTILE.

`payment_to_msrp_ratio`, `discount_amount`, and `discount_percent` are
generated columns persisted by Postgres — read-only on the ORM.
"""

from __future__ import annotations

from datetime import date, datetime
from decimal import Decimal

from sqlalchemy import (
    CHAR,
    DECIMAL,
    BigInteger,
    Boolean,
    Date,
    ForeignKey,
    Integer,
    SmallInteger,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import TIMESTAMP
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class MarketDeal(Base):
    __tablename__ = "market_deals"

    deal_id:                 Mapped[int]            = mapped_column(BigInteger, primary_key=True)

    make_name:               Mapped[str]            = mapped_column(String(100), nullable=False)
    model_name:              Mapped[str]            = mapped_column(String(200), nullable=False)
    trim_name:               Mapped[str | None]     = mapped_column(String(200))
    model_year:              Mapped[int]            = mapped_column(SmallInteger, nullable=False)
    trim_id:                 Mapped[int | None]     = mapped_column(ForeignKey("vehicle_trims.trim_id"))

    province_code:           Mapped[str | None]     = mapped_column(CHAR(2), ForeignKey("provinces.province_code"))
    city:                    Mapped[str | None]     = mapped_column(String(100))

    msrp:                    Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2))
    cap_cost:                Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2))
    # Generated by the DB.
    discount_amount:         Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2))
    discount_percent:        Mapped[Decimal | None] = mapped_column(DECIMAL(6, 4))
    down_payment:            Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2), default=Decimal("0"))
    cash_incentives_applied: Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2), default=Decimal("0"))

    term_months:             Mapped[int | None]     = mapped_column(SmallInteger)
    km_allowance_annual:     Mapped[int | None]     = mapped_column(Integer)
    lease_rate_percent:      Mapped[Decimal | None] = mapped_column(DECIMAL(6, 4))
    residual_percent:        Mapped[Decimal | None] = mapped_column(DECIMAL(6, 4))
    residual_amount:         Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2))

    monthly_payment_pretax:  Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2))
    monthly_payment_total:   Mapped[Decimal | None] = mapped_column(DECIMAL(10, 2))
    payment_to_msrp_ratio:   Mapped[Decimal | None] = mapped_column(DECIMAL(6, 4))

    deal_month:              Mapped[date | None]    = mapped_column(Date)
    days_on_lot_at_deal:     Mapped[int | None]     = mapped_column(Integer)
    dealer_id:               Mapped[int | None]     = mapped_column(ForeignKey("dealers.dealer_id"))
    was_month_end:           Mapped[bool | None]    = mapped_column(Boolean)

    source:                  Mapped[str]            = mapped_column(String(50), nullable=False)
    source_listing_id:       Mapped[str | None]     = mapped_column(String(300))
    quality_score:           Mapped[int]            = mapped_column(SmallInteger, nullable=False, default=3)
    notes:                   Mapped[str | None]     = mapped_column(Text)
    created_at:              Mapped[datetime]       = mapped_column(TIMESTAMP(timezone=True), nullable=False)
